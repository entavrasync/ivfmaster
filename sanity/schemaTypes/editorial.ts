import { CircleHelp, Images, BookOpen } from 'lucide-react'
import { defineArrayMember, defineField, defineType } from 'sanity'
import { validateWebsiteImage } from '../lib/image-validation'
import { aboutInformationContent, facilityAreas, facilityGalleryContent, homeFaqContent } from '../lib/editorial-mapping.ts'
import { approvalField, localizedField } from './editorial-fields.ts'

const copy = (name: string, title = name) => localizedField(name, title, true)
const array = (name: string, fields: ReturnType<typeof localizedField>[], min: number, max: number) => defineField({
  name, type: 'array', of: [defineArrayMember({ name: `${name}Entry`, type: 'object', fields })], validation: (r) => r.required().min(min).max(max),
})

export const homeFaq = defineType({
  name: 'homeFaq', title: 'Homepage questions', type: 'document', icon: CircleHelp,
  description: 'One approved published document supplies the existing homepage accordion. Keep CTA labels/URLs in code. Ordinary IDs are generated by Sanity.',
  fields: [approvalField, copy('eyebrow'), copy('heading'), copy('body', 'Introduction'), copy('closeBody', 'Closing explanation'),
    array('faqs', [copy('question'), copy('answer')], 1, 20),
  ],
  validation: (r) => r.custom((value) => homeFaqContent.safeParse(value).success || 'Complete all English text and provide unique questions/array keys. Use plain text; Marathi is optional.'),
  preview: { select: { title: 'heading.en' } },
})

export const aboutInformation = defineType({
  name: 'aboutInformation', title: 'About: clinic approach', type: 'document', icon: BookOpen,
  description: 'Clinic origin, four care steps and care principles only. No patient stories, personnel, hero or promotional layout configuration.',
  fields: [approvalField,
    defineField({ name: 'origin', type: 'object', fields: [copy('eyebrow'), copy('title'), copy('quote'), copy('note'),
      defineField({ name: 'paragraphs', type: 'array', of: [defineArrayMember({ type: 'procedureLocalizedText' })], validation: (r) => r.required().min(1).max(10) }),
    ], validation: (r) => r.required() }),
    defineField({ name: 'care', type: 'object', fields: [copy('eyebrow'), copy('title'), copy('intro'), array('steps', [copy('title'), copy('body')], 4, 4)], validation: (r) => r.required() }),
    defineField({ name: 'trust', type: 'object', fields: [copy('eyebrow'), copy('title'), copy('intro'), array('points', [copy('label'), copy('title'), copy('body')], 1, 10)], validation: (r) => r.required() }),
  ],
  validation: (r) => r.custom((value) => aboutInformationContent.safeParse(value).success || 'Complete the English origin, four care steps and care principles. Use unique paragraphs, principle titles and array keys; Marathi is optional.'),
  preview: { prepare: () => ({ title: 'About: clinic approach' }) },
})

export const facilityGallery = defineType({
  name: 'facilityGallery', title: 'Clinic facility gallery', type: 'document', icon: Images,
  description: 'The existing four Team-page facility areas, in their current layout order. Facility photographs only; patient imagery is outside this workflow.',
  fields: [approvalField, copy('eyebrow'), copy('heading'), copy('lead'),
    defineField({ name: 'areas', type: 'array', of: [defineArrayMember({ name: 'facilityArea', type: 'object', fields: [
      defineField({ name: 'area', type: 'string', options: { list: [...facilityAreas] }, validation: (r) => r.required() }),
      copy('caption'), copy('imageAlt', 'Shared area alternative text'),
      defineField({ name: 'images', type: 'array', description: 'Optional replacement photos, ordered within this area. Leave unset to retain the current static photos. Native assets need dimensions/LQIP metadata.',
        of: [defineArrayMember({ type: 'image', options: { hotspot: true, accept: 'image/jpeg,image/png,image/webp,image/avif' }, validation: (r) => [r.required().assetRequired(), r.custom(validateWebsiteImage)] })], validation: (r) => r.min(1).max(10),
      }),
    ] })], validation: (r) => r.required().length(4) }),
  ],
  validation: (r) => r.custom((value) => {
    // Studio holds native asset references; the frontend validates dereferenced metadata.
    const doc = value as { areas?: unknown[] } | undefined
    const areas = doc?.areas?.map((area) => area && typeof area === 'object' ? { ...area, images: undefined } : area)
    return facilityGalleryContent.safeParse({ ...doc, areas }).success || 'Complete all English copy and keep reception, consultation, laboratory, waiting in that order.'
  }),
  preview: { select: { title: 'heading.en' } },
})
